"""
Menu integration utilities for auto-populating Website Header Footer Config
when pages are generated by AI or manually created.
"""

import frappe
from frappe import _


def update_menu_after_page_creation(page_doc, add_to_menu: bool = True):
	"""
	Update the Website Header Footer Config menu after a Builder Page is created.

	Args:
		page_doc: The Builder Page document
		add_to_menu: Whether to add this page to the menu

	Returns:
		dict: The added menu item or None
	"""
	if not add_to_menu:
		return None

	try:
		config = frappe.get_single("Website Header Footer Config")
	except frappe.DoesNotExistError:
		# Config doesn't exist yet, nothing to update
		return None

	if not config.menu_items:
		config.menu_items = []

	# Don't add if already exists
	url = f"/{page_doc.route}" if page_doc.route else "/"
	for item in config.menu_items:
		if item.url == url:
			return None

	label = page_doc.page_title or page_doc.page_name

	config.append("menu_items", {
		"label": label,
		"url": url,
		"is_external": False,
		"open_in_new_tab": False,
	})
	config.save(ignore_permissions=True)

	return {
		"label": label,
		"url": url,
	}


def update_menu_from_generated_pages(pages: list[dict]):
	"""
	Update menu with multiple pages at once.

	Args:
		pages: List of page info dicts with keys:
			- title: Page title
			- route: Page route
			- add_to_menu: Whether to add to menu (default True)
			- menu_label: Optional custom menu label

	Returns:
		list: Added menu items
	"""
	try:
		config = frappe.get_single("Website Header Footer Config")
	except frappe.DoesNotExistError:
		return []

	added = []

	for page in pages:
		if not page.get("add_to_menu", True):
			continue

		url = f"/{page['route']}" if page.get("route") else "/"

		# Skip if already exists
		if any(item.url == url for item in (config.menu_items or [])):
			continue

		label = page.get("menu_label") or page.get("title", "Page")

		config.append("menu_items", {
			"label": label,
			"url": url,
			"is_external": False,
			"open_in_new_tab": False,
		})
		added.append({"label": label, "url": url})

	if added:
		config.save(ignore_permissions=True)

	return added


def sync_menu_with_pages(replace: bool = False):
	"""
	Synchronize menu items with published Builder Pages.

	Args:
		replace: If True, replace all menu items; if False, only add missing

	Returns:
		dict: Summary of changes
	"""
	try:
		config = frappe.get_single("Website Header Footer Config")
	except frappe.DoesNotExistError:
		return {"error": "Website Header Footer Config not found"}

	pages = frappe.get_all(
		"Builder Page",
		filters={"published": 1},
		fields=["name", "page_title", "route"],
		order_by="modified desc"
	)

	if replace:
		config.menu_items = []

	added = []
	skipped = []

	existing_urls = {item.url for item in (config.menu_items or [])}

	for page in pages:
		url = f"/{page.route}" if page.route else "/"

		if url in existing_urls:
			skipped.append(url)
			continue

		label = page.page_title or page.name
		config.append("menu_items", {
			"label": label,
			"url": url,
			"is_external": False,
			"open_in_new_tab": False,
		})
		added.append(url)
		existing_urls.add(url)

	if added or replace:
		config.save(ignore_permissions=True)

	return {
		"added": added,
		"skipped": skipped,
		"total_menu_items": len(config.menu_items or []),
	}


def sync_from_website_settings(doc, method):
	"""Sync Website Settings top_bar_items to Website Header Footer Config.

	Called via doc_events hook when Website Settings is updated.
	Uses _syncing flag to prevent infinite loops.
	"""
	if getattr(doc, "flags", None) and getattr(doc.flags, "_syncing", False):
		return

	try:
		config = frappe.get_single("Website Header Footer Config")
		config._syncing = True
		config.menu_items = []
		for item in (doc.top_bar_items or []):
			config.append("menu_items", {
				"label": item.label,
				"url": item.url,
				"is_external": 0,
				"open_in_new_tab": item.get("open_in_new_tab", 0),
			})
		config.save(ignore_permissions=True)
	except Exception:
		frappe.log_error("Menu sync from Website Settings failed", frappe.get_traceback())


